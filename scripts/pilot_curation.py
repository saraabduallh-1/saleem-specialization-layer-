CONTRAST_TYPES = ("different_sense", "different_domain", "abbreviation_collision")


def N(ex, intended_sense, why, contrast_type):
    """Negative/context example.

    contrast_type (Engineering Decision — labelling rule used for the pilot):
      different_sense        the surface word carries a genuinely different lexical meaning
                             (e.g. نموذج = form/template, الوزن الصرفي, تأسيس شركة, التحيز الخوارزمي vs bias parameter).
      different_domain       the same core meaning used in another field, of which the AI sense is an
                             extension (e.g. طبقة الأوزون, الدورة الاقتصادية, محول كهربائي, هلوسة طبية).
      abbreviation_collision only the abbreviation coincides (e.g. CNN the news channel).
    """
    assert contrast_type in CONTRAST_TYPES, contrast_type
    ex = dict(ex)
    ex["intended_sense"] = intended_sense
    ex["why_not_this_term"] = why
    ex["contrast_type"] = contrast_type
    return ex


